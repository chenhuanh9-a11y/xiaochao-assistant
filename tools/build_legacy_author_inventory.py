"""Reproduce the legacy display-only inventory from four approved release ZIPs.

Usage: python tools/build_legacy_author_inventory.py SERVER_STAGING
No installed files are a trust source. Images are never copied into the repository.
"""
import hashlib
import json
from pathlib import Path
import pprint
import sys
import zipfile

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'app'))
from star_map_import import _allowed, _live_author_path, _rows

APPROVED = {
    'nightmare-suju': ('star-maps-nightmare-suju-20261027-r1.zip', 'fe01b53068f8b4e00469e25d5a6886ba24befc927b189a378a41dcdf3d588891'),
    'difficult-zhan10': ('star-maps-difficult-zhan10-native58-legacy2-20261027-r6.zip', '3dc1198c34bff688d6db3bfeedcd5b0cf041d218a7e654c808bc21fee97c4dff'),
    'nightmare-wang-qingxin': ('star-maps-nightmare-wang-qingxin-20261027-r1.zip', 'ddc2e4e372201506a3efbe10323e4f1db8176e54cd4a237759b13491c7e624dd'),
    'nightmare-nightingale': ('star-maps-nightmare-nightingale-20261027-r1.zip', 'adaa7169ae94706e5dfd6bb13a1dac4220c2684a2aff2dedb53477d99c087be6'),
}


def build(directory):
    inventory = {}
    for package, (name, digest) in APPROVED.items():
        archive_path = Path(directory) / 'packages' / name
        with archive_path.open('rb') as source:
            assert hashlib.file_digest(source, 'sha256').hexdigest() == digest, name
        with zipfile.ZipFile(archive_path) as archive:
            metadata = json.loads(archive.read('map-package.json'))
            assert metadata['packageId'] == package
            rows = _rows(metadata['files'])
            display = []
            for row in rows.values():
                if not _live_author_path(package, row['path']):
                    continue
                assert _allowed(package, row['path'])
                payload = archive.read('data/' + row['path'])
                assert len(payload) == row['bytes']
                assert hashlib.sha256(payload).hexdigest() == row['sha256']
                display.append(dict(row, role='author-sidecar' if '/author-packs/' in row['path'] else 'author-image'))
            assert display
            inventory[package] = dict(archiveSha256=digest, archiveName=name,
                                     files=sorted(display, key=lambda row: row['path']))
    return inventory


if __name__ == '__main__':
    data = build(sys.argv[1])
    output = ROOT / 'app' / 'legacy_author_inventory.py'
    output.write_text('"""Approved 20261027 display hashes; generated by tools/build_legacy_author_inventory.py.\n'
                      'No images, structures, requiresFiles or local paths are embedded.\n"""\n'
                      'LEGACY_AUTHOR_INVENTORY = ' + pprint.pformat(data, width=120, sort_dicts=True) + '\n', encoding='utf-8')
    print(json.dumps({key: len(value['files']) for key, value in data.items()}))

