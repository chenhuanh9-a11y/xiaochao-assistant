"""Export only reviewed Android grid identities; never copy art or road data.

Reads fixed paths at an explicit Git ref without checking out the Android repo.
Compatible signatures must be covered by the pinned legacy catalog and its
unchanged per-floor grids. New compatibility sources require an explicit review.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
from pprint import pformat
import re
import subprocess

ASSET_ROOT = "mobile/app/src/main/assets/nightmare-route-editor/"
LEGACY_ROOT = "mobile/scripts/assets/nightmare-route-legacy/editor/"
GEOMETRY = ("width", "height", "step", "cols", "rows")
SIGNATURE = re.compile(r"[a-f0-9]{64}")
TEMPLATE = re.compile(r"nightmare-layout-(0[1-9]|[12]\d)")
FLOORS = {"minus-1": "B1", "1": "1", "2": "2"}


def require(condition, message):
    if not condition:
        raise ValueError(message)


def grid(data):
    result = {key: data[key] for key in GEOMETRY}
    require(data["version"] == 1 and all(type(v) is int and v > 0 for v in result.values()),
            "Unsupported navigation grid")
    require(result["step"] == 2 and result["cols"] == (result["width"] + 1) // 2
            and result["rows"] == (result["height"] + 1) // 2, "Grid differs from PC's 2px contract")
    return result


def export_catalog(read_json):
    """read_json takes a fixed repo-relative path; injectable for synthetic tests."""
    catalog = read_json(ASSET_ROOT + "catalog.json")
    legacy = read_json(LEGACY_ROOT + "catalog.json")
    migration = read_json(ASSET_ROOT + "migration.json")
    require(type(catalog["navigationVersion"]) is int and catalog["navigationVersion"] == 1
            and legacy["navigationVersion"] == 1 and migration["version"] == 1,
            "Unsupported catalog/migration version")
    previous = {t["id"]: t for t in legacy["templates"]}
    templates = {}
    for template in catalog["templates"]:
        tid = template["id"]
        require(isinstance(tid, str) and TEMPLATE.fullmatch(tid) and tid not in templates, "Invalid/duplicate template")
        signature = template["navigationSignature"]
        compatible = template.get("compatibleNavigationSignatures", [])
        require(isinstance(signature, str) and SIGNATURE.fullmatch(signature)
                and isinstance(compatible, list) and all(isinstance(s, str) and SIGNATURE.fullmatch(s) for s in compatible)
                and len(set(compatible)) == len(compatible) and signature not in compatible, "Invalid signatures")
        old = previous.get(tid)
        if compatible:
            require(old is not None and set(compatible) == {old["navigationSignature"], *old.get("compatibleNavigationSignatures", [])},
                    f"{tid}: compatible signatures need a reviewed legacy grid source")
            require(set(migration["templates"][tid]["signatures"]) == set(compatible),
                    f"{tid}: migration/signature registry differs")
            require({f["id"] for f in old["floors"]} == {f["id"] for f in template["floors"]},
                    f"{tid}: compatible floors changed")
        floors = {}
        for floor in template["floors"]:
            fid = floor["id"]
            require(fid in FLOORS and FLOORS[fid] not in floors, f"{tid}: invalid/duplicate floor")
            path = f"navigation/n{tid[-2:]}-{fid}.json"
            require(floor["navigation"] == path, f"{tid}: unexpected navigation path")
            geometry = grid(read_json(ASSET_ROOT + path))
            require((floor["width"], floor["height"]) == (geometry["width"], geometry["height"]),
                    f"{tid}/{fid}: catalog/grid sizes differ")
            if compatible:
                old_floor = next(f for f in old["floors"] if f["id"] == fid)
                require(old_floor["navigation"] == path and grid(read_json(LEGACY_ROOT + path)) == geometry
                        and (old_floor["width"], old_floor["height"]) == (floor["width"], floor["height"])
                        and old_floor["sha256"] == floor.get("navigationSourceSha256", floor["sha256"]),
                        f"{tid}/{fid}: compatible grid/template art changed")
            floors[FLOORS[fid]] = geometry
        require(set(floors) == set(FLOORS.values()), f"{tid}: incomplete floors")
        templates[tid] = dict(navigationSignature=signature, compatibleNavigationSignatures=sorted(compatible), floors=floors)
    require(bool(templates), "Empty navigation catalog")
    return catalog["navigationVersion"], templates


def render(source, version, templates):
    return ("# Generated by tools/maps/sync_route_plaza_navigation.py; do not edit by hand.\n"
            '"""Public grid identities only: no images, rooms, road edges or author routes."""\n\n'
            + "SOURCE = " + pformat(source, sort_dicts=True, width=110) + "\n\n"
            + f"NAVIGATION_VERSION = {version}\n\n"
            + "TEMPLATES = " + pformat(templates, sort_dicts=True, width=110) + "\n")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--android-repo", type=Path, required=True, help="Explicit authorized Android checkout (read only)")
    parser.add_argument("--ref", required=True, help="Explicit local Git ref or commit; no fetch or checkout")
    parser.add_argument("--output", type=Path, default=Path(__file__).resolve().parents[2] / "app/route_plaza_navigation.py")
    parser.add_argument("--check", action="store_true", help="Compare generated bytes without writing")
    args = parser.parse_args()

    def git(*arguments):
        return subprocess.check_output(["git", "-C", str(args.android_repo), *arguments])

    commit = git("rev-parse", "--verify", "--end-of-options", args.ref + "^{commit}").decode().strip()
    hashes = {}

    def read_json(path):
        raw = git("show", commit + ":" + path)
        hashes[path] = hashlib.sha256(raw).hexdigest()
        return json.loads(raw)

    version, templates = export_catalog(read_json)
    source = dict(commit=commit, reference=args.ref, inputSha256=hashes)
    content = render(source, version, templates).encode("utf-8")
    if args.check:
        require(args.output.read_bytes() == content, "Navigation registry is out of sync")
    else:
        args.output.write_bytes(content)
    print(f"{len(templates)} templates, {sum(len(t['floors']) for t in templates.values())} floors; "
          f"SHA256 {hashlib.sha256(content).hexdigest()}")


if __name__ == "__main__":
    main()
